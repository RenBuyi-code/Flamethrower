/* ======================== 8x16 字体绘制回调 ======================== */

/**
 * @brief  8x16 ASCII 字体绘制回调（逐列式 + 低位在前）
 * @param  x      起始像素 X 坐标
 * @param  y      起始像素 Y 坐标
 * @param  str    待绘制的字符串
 * @param  font   字体对象指针（本字体不使用此参数）
 * @param  color  绘制颜色 (0=灭, 1=亮)
 * @retval 绘制结束后的 X 坐标
 *
 * 数据布局（与 PCtoLCD2002 逐列式 + 低位在前匹配）：
 *   bitmap[col*2]     = 第 col 列，rows 0-7（bit0=row0, bit7=row7）
 *   bitmap[col*2 + 1] = 第 col 列，rows 8-15（bit0=row8, bit7=row15）
 *   每字符 16 字节 = 8 列 × 每列 2 字节 */
static uint16_t ascii_8x16_draw(uint16_t x, uint16_t y, const char *str,
                               const void *font, uint8_t color) {
    (void)font;
    const uint8_t *p = (const uint8_t *)str;
    while (*p) {
        if (*p >= 0x20 && *p <= 0x7E) {
            uint8_t idx = (uint8_t)(*p - 0x20);
            const uint8_t *bitmap = sl_ascii_8x16_data[idx];
            int col;
            for (col = 0; col < 8; col++) {
                uint8_t lo = bitmap[col * 2];
                uint8_t hi = bitmap[col * 2 + 1];
                int row;
                for (row = 0; row < 8; row++) {
                    if (lo & ((uint8_t)1 << row)) {
                        sl_disp_draw_pixel((int)(x + col), (int)(y + row), color);
                    }
                    if (hi & ((uint8_t)1 << row)) {
                        sl_disp_draw_pixel((int)(x + col), (int)(y + 8 + row), color);
                    }
                }
            }
        }
        x += 8;
        p++;
    }
    return x;
}

