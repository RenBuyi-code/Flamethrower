/* ======================== 汉字索引查找 ======================== */

/**
 * @brief  通过 Unicode 码点查找汉字在字模表中的索引（线性搜索）
 * @param  unicode  Unicode 码点
 * @retval 索引值 (0 ~ SL_CHINESE_GLYPH_COUNT-1)
 * @retval 0xFFFF 表示未找到该汉字
 * @note   遍历 g_glyph_unicode[]，添加新字无需修改此函数
 */
uint16_t sl_chinese_index(uint16_t unicode) {
    int i;
    for (i = 0; i < SL_CHINESE_GLYPH_COUNT; i++) {
        if (g_glyph_unicode[i] == unicode) {
            return (uint16_t)i;
        }
    }
    return 0xFFFF;
}

/* ======================== 16x16 中文绘制回调 ======================== */

/**
 * @brief  16x16 中文绘制回调
 * @param  x      起始像素 X 坐标
 * @param  y      起始像素 Y 坐标
 * @param  str    待绘制的字符串（UTF-8 编码，每个汉字 3 字节）
 * @param  font   字体对象指针（本字体不使用此参数）
 * @param  color  绘制颜色 (0=灭, 非0=亮)
 * @retval 绘制结束后的 X 坐标
 *
 * 绘制流程：
 *   1. 逐字符解析 UTF-8 序列；
 *   2. ASCII 字符 (0x20~0x7E)：回退到 8x16 ASCII 字体绘制；
 *   3. 汉字 (UTF-8 三字节)：提取 Unicode 码点，查表获取索引，
 *      从 sl_chinese_glyphs 取 32 字节数据，逐列绘制；
 *   4. ASCII 前进 8 像素，汉字前进 16 像素。
 */
static uint16_t chinese_16x16_draw(uint16_t x, uint16_t y, const char *str,
                                   const void *font, uint8_t color) {
    (void)font;
    const uint8_t *p = (const uint8_t *)str;

    while (*p) {
        if (*p >= 0x20 && *p <= 0x7E) {
            /* 回退到 8x16 ASCII 字体绘制单个 ASCII 字符 */
            uint8_t idx = *p - 0x20;
            extern const uint8_t sl_ascii_8x16_data[95][16];
            extern uint16_t ascii_8x16_draw(uint16_t, uint16_t, const char*, const void*, uint8_t);
            char tmp[2] = {(char)*p, '\0'};
            x = ascii_8x16_draw(x, y, tmp, NULL, color);
            p++;
        } else if ((*p & 0xE0) == 0xE0 && *(p+1) && *(p+2)) {
            /* UTF-8 汉字：3 字节 → 提取 Unicode 码点 */
            uint16_t unicode = ((uint16_t)(*p & 0x0F) << 12) |
                               ((uint16_t)(*(p+1) & 0x3F) << 6) |
                               (uint16_t)(*(p+2) & 0x3F);

            uint16_t idx = sl_chinese_index(unicode);
            if (idx != 0xFFFF && idx < SL_CHINESE_GLYPH_COUNT) {
                const uint8_t *bitmap = sl_chinese_glyphs[idx];
                for (int col = 0; col < 16; col++) {
                    uint8_t lo = bitmap[col * 2];
                    uint8_t hi = bitmap[col * 2 + 1];
                    for (int row = 0; row < 8; row++) {
                        if (lo & (1u << row))
                            sl_disp_draw_pixel((int)(x + col), (int)(y + row), color);
                        if (hi & (1u << row))
                            sl_disp_draw_pixel((int)(x + col), (int)(y + 8 + row), color);
                    }
                }
            }
            x += 16;
            p += 3;
        } else {
            p++;
        }
    }
    return x;
}

